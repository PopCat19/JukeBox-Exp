// Generate Tabler icon data URIs for CSS custom properties
//
// Purpose: Reads tabler SVG files and prints CSS custom property declarations
// with URL-encoded SVG data URIs for use as mask-image.
//
// Run: bun scripts/generate-icon-uris.mjs

import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

function tablerIcon(subdir, name) {
  const p = resolve(root, "node_modules/@tabler/icons/icons", subdir, `${name}.svg`);
  if (!existsSync(p)) {
    console.error(`MISSING: ${p}`);
    return null;
  }
  let svg = readFileSync(p, "utf-8")
    .replace(/\n/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  // Remove class attribute — not needed in data URI
  svg = svg.replace(/ class="[^"]*"/g, "");
  // URL-encode for data URI
  // Use %22 for double quotes so CSS url("...") is safe
  const encoded = svg
    .replace(/#/g, "%23")
    .replace(/"/g, "%22");
  return encoded;
}

